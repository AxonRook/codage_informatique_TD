# La liste de fruits
fruits = ["pomme", "banane", "orange"]

# Ajout du kiwi à la liste
fruits.append("kiwi")

# Retrait de l'orange de la liste
fruits.remove("orange")

# Modification du deuxième fruit dans la liste
fruits[1] = "ananas"

# Affichage de la longueur de la liste
print("Longueur de la liste de fruits :", len(fruits))

# Tri et affichage de la liste de fruits par ordre alphabétique
fruits.sort()
print("Liste de fruits triée :", fruits)